import type { ChatMode } from "./chat";

/** המסכים שאפשר לפתוח מתוך הצ'אט */
export type ChatView = "list" | "shop";

const STORE_NAMES =
  "סופר|חנות|מכולת|שופרסל|רמי\\s*לוי|יוחננוף|ויקטורי|מגה|טיב\\s*טעם|אושר\\s*עד|יינות\\s*ביתן|חצי\\s*חינם|קרפור|קשת\\s*טעמים";

/** "אני בסופר", "הגעתי לשופרסל", "יוצא לקניות" */
const SHOP_ENTER: RegExp[] = [
  new RegExp(`(אני|אנחנו)\\s+(נמצא\\s+|נמצאת\\s+|נמצאים\\s+|עכשיו\\s+)?ב(${STORE_NAMES})`),
  new RegExp(`(הגעתי|הגענו|נכנסתי|נכנסנו)\\s+ל(${STORE_NAMES})`),
  /(יוצא|יוצאת|יוצאים|יצאתי|יצאנו|הולך|הולכת|הולכים)\s+(ל|לעשות\s+)?(סופר|קניות|לקנות)/,
  /(מתחיל|מתחילה|מתחילים)\s+(את\s+ה|ב|ל)?(קנייה|קניה|קניות|לקנות)/,
  new RegExp(`^ב(${STORE_NAMES})$`),
];

/** "יצאתי מהסופר", "חזרתי הביתה" */
const SHOP_EXIT: RegExp[] = [
  new RegExp(`(יצאתי|יצאנו)\\s+מ(ה)?(${STORE_NAMES})`),
  /(חזרתי|חזרנו|הגעתי|הגענו)\s+הביתה/,
  /(סיימתי|סיימנו)\s+(את\s+ה|עם\s+ה)?(קנייה|קניה|קניות|לקנות|סופר)/,
  /(אני|אנחנו)\s+(כבר\s+)?בבית/,
];

/** מילים שמעידות על שינוי ברשימה — גוברות על ניסוח של שאלה */
const LIST_CHANGE =
  /(תוסיף|תוסיפי|להוסיף|הוסף|תכניס|צריך|צריכה|צריכים|נגמר|נגמרה|נגמרו|חסר|חסרה|חסרים|אין\s+לנו|תקנה|תקני|קניתי|קנינו|לקחתי|תמחק|תמחקי|תוריד|תורידי|תסמן|תסמני)/;

/** "מה ההבדל", "איך בוחרים", "מה יותר בריא", או כל משפט שמסתיים בסימן שאלה */
const QUESTION =
  /(^|\s)(מה\s+ההבדל|איך|האם|למה|כדאי|עדיף|מומלץ|תחליף|כמה\s+(קלוריות|חלבון|סוכר|זמן)|מה\s+(יותר\s+)?(בריא|כדאי|עדיף|מומלץ|טוב))/;

/**
 * מזהה את מצב הצ'אט מהשפה של ההודעה.
 * מצב סופר נשאר עד שהמשתמש אומר שיצא — שאלה באמצע הקנייה לא מוציאה ממנו.
 * בין רגיל לייעוץ ההכרעה היא לכל הודעה בנפרד.
 */
export function detectMode(text: string, current: ChatMode): ChatMode {
  const t = text.trim();
  if (!t) return current;

  if (current === "shop") {
    return SHOP_EXIT.some((r) => r.test(t)) ? "normal" : "shop";
  }
  if (SHOP_ENTER.some((r) => r.test(t))) return "shop";
  if (LIST_CHANGE.test(t)) return "normal";
  if (/[?？]\s*$/.test(t) || QUESTION.test(t)) return "consult";
  return "normal";
}

const SHOW = "(תראה|תראי|הראה|תציג|תציגי|הצג|פתח|תפתח|תפתחי|לפתוח|להראות|אפשר\\s+לראות|רוצה\\s+לראות|בוא\\s+נראה)";

const VIEW_PATTERNS: { view: ChatView; re: RegExp }[] = [
  {
    view: "shop",
    re: new RegExp(
      `(${SHOW}\\s+(לי\\s+)?(את\\s+)?(מסך\\s+)?(ה)?(קנייה|קניה|קניות)|מסך\\s+(ה)?(קנייה|קניה)|${SHOW}\\s+(לי\\s+)?מה\\s+(נשאר\\s+)?לקנות)`
    ),
  },
  {
    view: "list",
    re: new RegExp(
      `(${SHOW}\\s+(לי\\s+)?(את\\s+)?(מסך\\s+)?(ה)?רשימה|מסך\\s+(ה)?רשימה|^מה\\s+(יש\\s+)?ב?רשימה\\s*[?？]?$|^(ה)?רשימה\\s*[?？]?$)`
    ),
  },
];

/** האם ההודעה מבקשת לפתוח את מסך הרשימה או מסך הקנייה */
export function detectViewRequest(text: string): ChatView | null {
  const t = text.trim();
  if (!t) return null;
  return VIEW_PATTERNS.find((p) => p.re.test(t))?.view ?? null;
}
